package com.fetch.tv.data.youtube

import kotlinx.serialization.json.Json
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

class YouTubeCaptionsTest {

    private val service = YouTubeCaptionService()

    private fun captions(vararg tracks: String, translations: String = "") = Json.parseToJsonElement(
        """{"playerCaptionsTracklistRenderer": {
            "captionTracks": [${tracks.joinToString(",")}],
            "translationLanguages": [$translations]
        }}"""
    )

    private fun track(lang: String, url: String, asr: Boolean = false, translatable: Boolean = true) =
        """{"baseUrl": "$url", "languageCode": "$lang", "name": {"simpleText": "$lang name"},
            ${if (asr) "\"kind\": \"asr\"," else ""} "isTranslatable": $translatable}"""

    @Test
    fun `the same track from two clients is one track with both links`() {
        val tracks = service.tracks(
            listOf(
                captions(track("en", "https://a.example/en")),
                captions(track("en", "https://b.example/en"), track("de", "https://b.example/de"))
            ),
            translateInto = emptyList()
        )

        assertEquals(listOf("en", "de"), tracks.map { it.languageCode })
        assertEquals(listOf("https://a.example/en", "https://b.example/en"), tracks[0].urls)
    }

    @Test
    fun `a missing language is translated from the automatic track`() {
        val tracks = service.tracks(
            listOf(
                captions(
                    track("en", "https://a.example/manual"),
                    track("en", "https://a.example/asr", asr = true),
                    translations = """{"languageCode": "fr", "languageName": {"simpleText": "French"}},
                        {"languageCode": "es", "languageName": {"simpleText": "Spanish"}}"""
                )
            ),
            translateInto = listOf("fr", "en")
        )

        val french = tracks.single { it.isTranslated }
        assertEquals("fr", french.languageCode)
        assertEquals("French", french.name)
        assertEquals(listOf("https://a.example/asr&tlang=fr"), french.urls)
        // English exists, and Spanish wasn't asked for.
        assertEquals(3, tracks.size)
    }

    @Test
    fun `relative links are made absolute`() {
        val tracks = service.tracks(listOf(captions(track("en", "/api/timedtext?v=x"))), emptyList())

        assertEquals("https://www.youtube.com/api/timedtext?v=x", tracks.single().urls.single())
    }

    @Test
    fun `the default prefers people's captions, then automatic, then translations, in language order`() {
        val manual = YouTubeCaptionTrack("en", "English", isAutoGenerated = false, isTranslated = false, urls = listOf("m"))
        val auto = manual.copy(isAutoGenerated = true, urls = listOf("a"))
        val translated = YouTubeCaptionTrack("fr", "French", isAutoGenerated = true, isTranslated = true, urls = listOf("t"))

        assertEquals(manual, pickDefaultCaptionTrack(listOf(auto, manual, translated), listOf("en")))
        assertEquals(auto, pickDefaultCaptionTrack(listOf(auto, translated), listOf("en", "fr")))
        assertEquals(translated, pickDefaultCaptionTrack(listOf(auto, translated), listOf("fr", "en")))
        assertNull(pickDefaultCaptionTrack(listOf(auto), listOf("ja")))
    }

    @Test
    fun `a language matches its regions, a region only itself`() {
        assertTrue(languageMatches("en-US", "en"))
        assertTrue(languageMatches("en", "en"))
        assertFalse(languageMatches("en-GB", "en-US"))
        assertFalse(languageMatches("eu", "en"))
    }

    @Test
    fun `json3 events become cues, and layout-only events are dropped`() {
        val cues = service.parseJson3(
            Json.parseToJsonElement(
                """{"events": [
                    {"tStartMs": 0, "dDurationMs": 5000, "id": 1, "wpWinPosId": 1},
                    {"tStartMs": 1200, "dDurationMs": 2000, "segs": [{"utf8": "Hello"}, {"utf8": " world"}]},
                    {"tStartMs": 3500, "dDurationMs": 1500, "segs": [{"utf8": "\n"}]},
                    {"tStartMs": 4000, "dDurationMs": 1000, "segs": [{"utf8": "Bye"}]}
                ]}"""
            )
        )

        assertEquals(
            listOf(YouTubeCaptionCue(1200, 3200, "Hello world"), YouTubeCaptionCue(4000, 5000, "Bye")),
            cues
        )
    }

    @Test
    fun `the cue at a position is found, and gaps show nothing`() {
        val cues = listOf(
            YouTubeCaptionCue(1000, 2000, "one"),
            YouTubeCaptionCue(3000, 5000, "two"),
            YouTubeCaptionCue(4000, 6000, "three")
        )

        assertNull(cueAt(cues, 500))
        assertEquals("one", cueAt(cues, 1500)?.text)
        assertNull(cueAt(cues, 2500))
        assertEquals("two", cueAt(cues, 3500)?.text)
        assertEquals("three", cueAt(cues, 4500)?.text)
        assertEquals("three", cueAt(cues, 5500)?.text)
        assertNull(cueAt(cues, 6000))
        assertNull(cueAt(emptyList(), 0))
    }

    @Test
    fun `captions are always asked for in json3`() {
        val url = service.withFormat("https://www.youtube.com/api/timedtext?v=x&fmt=srv3&lang=en")

        assertTrue(url.contains("fmt=json3"))
        assertFalse(url.contains("srv3"))
    }
}
