package com.fetch.tv.data.youtube

import android.util.Log
import com.fetch.tv.core.network.IPv4FirstDns
import com.fetch.tv.core.network.NoDelaySocketFactory
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.booleanOrNull
import kotlinx.serialization.json.contentOrNull
import kotlinx.serialization.json.longOrNull
import okhttp3.HttpUrl.Companion.toHttpUrlOrNull
import okhttp3.OkHttpClient
import okhttp3.Request
import java.util.Locale
import java.util.concurrent.TimeUnit
import javax.inject.Inject
import javax.inject.Singleton

private const val TAG = "YouTubeCaptions"

/**
 * A subtitle a YouTube video has. [urls] are the same track as listed by each player response
 * Fetch asked; some clients' links need a token Fetch doesn't have, so the next one is tried.
 */
data class YouTubeCaptionTrack(
    val languageCode: String,
    val name: String,
    val isAutoGenerated: Boolean,
    /** Set when YouTube translates the track into this language rather than having one. */
    val isTranslated: Boolean,
    val urls: List<String>
) {
    val id: String
        get() = "$languageCode|$isAutoGenerated|$isTranslated"
}

data class YouTubeCaptionCue(
    val startMs: Long,
    val endMs: Long,
    val text: String
)

/**
 * Reads a video's caption tracks from its player responses and downloads the chosen one, as
 * SmartTube does (innertube/utils/PlayerResultExtensions.kt). Captions come as YouTube's json3
 * format, which keeps each cue's timing and text and needs no subtitle renderer.
 */
@Singleton
class YouTubeCaptionService @Inject constructor() {
    private val json = Json { ignoreUnknownKeys = true }

    private val httpClient by lazy {
        OkHttpClient.Builder()
            .dns(IPv4FirstDns())
            .socketFactory(NoDelaySocketFactory)
            .connectTimeout(10, TimeUnit.SECONDS)
            .readTimeout(15, TimeUnit.SECONDS)
            .build()
    }

    /**
     * The tracks listed across [captionsBlocks] (each a player response's `captions`), merged so a
     * track any client lists appears once. Translations are offered only into [translateInto],
     * the viewer's subtitle languages, and only when the video has no track in that language.
     */
    fun tracks(captionsBlocks: List<JsonElement?>, translateInto: List<String>): List<YouTubeCaptionTrack> {
        val merged = linkedMapOf<String, YouTubeCaptionTrack>()
        val translatable = mutableSetOf<String>()
        val translationLanguages = linkedMapOf<String, String>()

        for (block in captionsBlocks) {
            val renderer = (block as? JsonObject)?.get("playerCaptionsTracklistRenderer") as? JsonObject ?: continue
            (renderer["captionTracks"] as? JsonArray).orEmpty().forEach { element ->
                val track = element as? JsonObject ?: return@forEach
                val baseUrl = track.string("baseUrl")?.let(::absoluteUrl) ?: return@forEach
                val language = track.string("languageCode") ?: return@forEach
                val autoGenerated = track.string("kind") == "asr"
                val parsed = YouTubeCaptionTrack(
                    languageCode = language,
                    name = YouTubeResponseParser.text(track["name"]) ?: displayLanguage(language),
                    isAutoGenerated = autoGenerated,
                    isTranslated = false,
                    urls = listOf(baseUrl)
                )
                merged[parsed.id] = merged[parsed.id]?.let { it.copy(urls = it.urls + baseUrl) } ?: parsed
                if (track.boolean("isTranslatable") == true) translatable += parsed.id
            }
            (renderer["translationLanguages"] as? JsonArray).orEmpty().forEach { element ->
                val language = (element as? JsonObject)?.string("languageCode") ?: return@forEach
                translationLanguages.putIfAbsent(
                    language,
                    YouTubeResponseParser.text(element["languageName"]) ?: displayLanguage(language)
                )
            }
        }

        val tracks = merged.values.toMutableList()
        // Like SmartTube, translate from the automatic track, which is in the spoken language.
        val source = tracks.firstOrNull { it.id in translatable && it.isAutoGenerated }
            ?: tracks.firstOrNull { it.id in translatable }
        if (source != null) {
            translateInto.distinct().forEach { wanted ->
                if (tracks.any { languageMatches(it.languageCode, wanted) }) return@forEach
                val language = translationLanguages.keys.firstOrNull { languageMatches(it, wanted) } ?: return@forEach
                tracks += YouTubeCaptionTrack(
                    languageCode = language,
                    name = translationLanguages.getValue(language),
                    isAutoGenerated = source.isAutoGenerated,
                    isTranslated = true,
                    urls = source.urls.map { "$it&tlang=$language" }
                )
            }
        }
        return tracks
    }

    /** The cues of [track], from the first of its links that gives any. */
    suspend fun cues(track: YouTubeCaptionTrack): List<YouTubeCaptionCue> = withContext(Dispatchers.IO) {
        for (url in track.urls) {
            val cues = runCatching { parseJson3(json.parseToJsonElement(download(withFormat(url)))) }
                .onFailure { Log.w(TAG, "Caption link failed: ${it.message}") }
                .getOrNull()
            if (!cues.isNullOrEmpty()) return@withContext cues
        }
        emptyList()
    }

    private fun download(url: String): String {
        val request = Request.Builder().url(url).get().build()
        httpClient.newCall(request).execute().use { response ->
            if (!response.isSuccessful) error("Captions returned ${response.code}")
            return response.body?.string().orEmpty()
        }
    }

    internal fun withFormat(url: String): String =
        url.toHttpUrlOrNull()?.newBuilder()?.setQueryParameter("fmt", "json3")?.build()?.toString() ?: url

    /** json3: `events` with `tStartMs`, `dDurationMs` and text `segs`; events without text only lay out. */
    internal fun parseJson3(root: JsonElement): List<YouTubeCaptionCue> {
        val events = (root as? JsonObject)?.get("events") as? JsonArray ?: return emptyList()
        return events.mapNotNull { element ->
            val event = element as? JsonObject ?: return@mapNotNull null
            val start = (event["tStartMs"] as? JsonPrimitive)?.longOrNull ?: return@mapNotNull null
            val duration = (event["dDurationMs"] as? JsonPrimitive)?.longOrNull ?: return@mapNotNull null
            val text = (event["segs"] as? JsonArray).orEmpty()
                .joinToString("") { (it as? JsonObject)?.string("utf8", allowBlank = true).orEmpty() }
                .trim()
            if (text.isEmpty() || duration <= 0L) null else YouTubeCaptionCue(start, start + duration, text)
        }.sortedBy { it.startMs }
    }

    private fun absoluteUrl(url: String) = if (url.startsWith("/")) "https://www.youtube.com$url" else url

    private fun JsonObject.string(key: String, allowBlank: Boolean = false): String? =
        (this[key] as? JsonPrimitive)?.takeIf { it.isString }?.contentOrNull?.takeIf { allowBlank || it.isNotBlank() }

    private fun JsonObject.boolean(key: String): Boolean? = (this[key] as? JsonPrimitive)?.booleanOrNull
}

/** "en" matches "en", "en-US" and "en-GB"; a regional preference matches only its region. */
internal fun languageMatches(trackLanguage: String, wanted: String): Boolean {
    val track = trackLanguage.lowercase(Locale.ROOT)
    val want = wanted.lowercase(Locale.ROOT)
    return track == want || (!want.contains('-') && track.substringBefore('-') == want)
}

private fun displayLanguage(code: String): String =
    Locale.forLanguageTag(code).getDisplayName(Locale.getDefault()).ifBlank { code }

/**
 * The track to show first: one in the viewer's language, made by people before YouTube's
 * automatic ones, then a translation into that language. Null when none is in their languages,
 * since a caption in a language they didn't ask for isn't a sensible default.
 */
internal fun pickDefaultCaptionTrack(tracks: List<YouTubeCaptionTrack>, languages: List<String>): YouTubeCaptionTrack? {
    for (language in languages) {
        val inLanguage = tracks.filter { languageMatches(it.languageCode, language) }
        inLanguage.firstOrNull { !it.isAutoGenerated && !it.isTranslated }?.let { return it }
        inLanguage.firstOrNull { !it.isTranslated }?.let { return it }
        inLanguage.firstOrNull()?.let { return it }
    }
    return null
}

/** The cue showing at [positionMs], found by binary search since cues are sorted by start. */
internal fun cueAt(cues: List<YouTubeCaptionCue>, positionMs: Long): YouTubeCaptionCue? {
    var low = 0
    var high = cues.lastIndex
    var candidate = -1
    while (low <= high) {
        val mid = (low + high) ushr 1
        if (cues[mid].startMs <= positionMs) {
            candidate = mid
            low = mid + 1
        } else {
            high = mid - 1
        }
    }
    // Overlapping cues happen in YouTube's rolling automatic captions; show the latest started.
    for (index in candidate downTo maxOf(0, candidate - 3)) {
        val cue = cues[index]
        if (positionMs < cue.endMs) return cue
    }
    return null
}
