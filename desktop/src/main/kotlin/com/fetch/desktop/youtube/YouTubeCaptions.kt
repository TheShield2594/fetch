/**
 * A caption track a YouTube video has, as the TV's `YouTubeCaptions.kt` reads them from the player
 * response. [urls] are YouTube's timedtext links for it. Fetch downloads the cues (as json3,
 * [YouTubeCaptions.cues]) and draws them itself in the player's subtitle style, as the TV's
 * caption renderer does; [webVttUrl] is for mpv when that download fails.
 */
data class YouTubeCaptionTrack(
    val languageCode: String,
    val name: String,
    val isAutoGenerated: Boolean,
    /** Set when YouTube translates the track into this language rather than having one. */
    val isTranslated: Boolean,
    val urls: List<String>
) {
    val id: String get() = "$languageCode|$isAutoGenerated|$isTranslated"

    /** "English", "English (auto-generated)", "German (auto-translated)": the TV's labels. */
    val label: String
        get() = when {
            isTranslated -> "$name (auto-translated)"
            isAutoGenerated -> "$name (auto-generated)"
            else -> name
        }

    /** The track's first link, asked for as WebVTT, which mpv reads. */
    val webVttUrl: String? get() = urls.firstOrNull()?.let(::withVttFormat)
}

/** Whether captions were on for the last video, and in which language: the TV's caption preference. */
@Serializable
data class YouTubeCaptionPreference(
    val enabled: Boolean = false,
    val languageCode: String? = null
)

object YouTubeCaptions {

    /**
     * The tracks listed across [captionsBlocks] (each a player response's `captions`), merged so a
     * track listed twice appears once. Translations are offered only into [translateInto], the
     * viewer's subtitle languages, and only when the video has no track in that language.
     */
    fun tracks(captionsBlocks: List<JsonElement?>, translateInto: List<String>): List<YouTubeCaptionTrack> {
        val merged = linkedMapOf<String, YouTubeCaptionTrack>()
        val translatable = mutableSetOf<String>()
        val translationLanguages = linkedMapOf<String, String>()
        for (block in captionsBlocks) {
            val renderer = (block as? JsonObject)?.get("playerCaptionsTracklistRenderer") as? JsonObject ?: continue
            (renderer["captionTracks"] as? JsonArray).orEmpty().forEach { element ->
                val track = element as? JsonObject ?: return@forEach
                val baseUrl = track.string("baseUrl")?.let(::absoluteUrl) ?: return@forEach
                val language = track.string("languageCode") ?: return@forEach
                val parsed = YouTubeCaptionTrack(
                    languageCode = language,
                    name = YouTubeResponseParser.text(track["name"])?.removeSuffix(" (auto-generated)") ?: displayLanguage(language),
                    isAutoGenerated = track.string("kind") == "asr",
                    isTranslated = false,
                    urls = listOf(baseUrl)
                )
                merged[parsed.id] = merged[parsed.id]?.let { it.copy(urls = it.urls + baseUrl) } ?: parsed
                if ((track["isTranslatable"] as? JsonPrimitive)?.booleanOrNull == true) translatable += parsed.id
            }
            (renderer["translationLanguages"] as? JsonArray).orEmpty().forEach { element ->
                val language = (element as? JsonObject)?.string("languageCode") ?: return@forEach
                translationLanguages.putIfAbsent(language, YouTubeResponseParser.text(element["languageName"]) ?: displayLanguage(language))
            }
        }
        val tracks = merged.values.toMutableList()
        // Like SmartTube, translate from the automatic track, which is in the spoken language.
        val source = tracks.firstOrNull { it.id in translatable && it.isAutoGenerated } ?: tracks.firstOrNull { it.id in translatable }
        if (source != null) {
            translateInto.distinct().forEach { wanted ->
                if (tracks.any { languageMatches(it.languageCode, wanted) }) return@forEach
                val language = translationLanguages.keys.firstOrNull { languageMatches(it, wanted) } ?: return@forEach
                tracks += YouTubeCaptionTrack(
                    languageCode = language,
                    name = translationLanguages.getValue(language),
                    isAutoGenerated = source.isAutoGenerated,
                    isTranslated = true,
                    urls = source.urls.map { "$it&tlang=$language" }
                )
            }
        }
        return tracks
    }

    /** The menu's order: the video's own tracks, then YouTube's automatic ones, then translations. */
    fun menuOrder(tracks: List<YouTubeCaptionTrack>): List<YouTubeCaptionTrack> =
        tracks.sortedWith(compareBy({ it.isTranslated }, { it.isAutoGenerated }, { it.name }))

    /**
     * The track to show first: one in the viewer's language made by people, before YouTube's
     * automatic ones, then a translation. Null when none is in their languages.
     */
    fun pickDefault(tracks: List<YouTubeCaptionTrack>, languages: List<String>): YouTubeCaptionTrack? {
        for (language in languages) {
            val inLanguage = tracks.filter { languageMatches(it.languageCode, language) }
            inLanguage.firstOrNull { !it.isAutoGenerated && !it.isTranslated }?.let { return it }
            inLanguage.firstOrNull { !it.isTranslated }?.let { return it }
            inLanguage.firstOrNull()?.let { return it }
        }
        return null
    }
}

/**
 * A track's cues: from the first of its links that gives any, as YouTube's json3 (the TV's
 * format: each event's start, duration and text), else as WebVTT. Empty when none do.
 */
fun YouTubeCaptions.cues(track: YouTubeCaptionTrack, download: (String) -> String?): List<Cue> {
    for (url in track.urls) {
        download(withFormat(url, "json3"))?.let(::parseJson3)?.takeIf { it.isNotEmpty() }?.let { return it }
        download(withVttFormat(url))?.let(CueParser::parse)?.takeIf { it.isNotEmpty() }?.let { return it }
    }
    return emptyList()
}

/** json3: `events` with `tStartMs`, `dDurationMs` and text `segs`; events without text only lay out. */
fun parseJson3(raw: String): List<Cue> = runCatching {
    val events = (Json.parseToJsonElement(raw) as? JsonObject)?.get("events") as? JsonArray ?: return emptyList()
    events.mapNotNull { element ->
        val event = element as? JsonObject ?: return@mapNotNull null
        val start = (event["tStartMs"] as? JsonPrimitive)?.longOrNull ?: return@mapNotNull null
        val duration = (event["dDurationMs"] as? JsonPrimitive)?.longOrNull ?: return@mapNotNull null
        val text = (event["segs"] as? JsonArray).orEmpty()
            .joinToString("") { ((it as? JsonObject)?.get("utf8") as? JsonPrimitive)?.contentOrNull.orEmpty() }
            .trim()
        if (text.isEmpty() || duration <= 0L) null else Cue(start, start + duration, text)
    }.sortedBy { it.startMs }
}.getOrDefault(emptyList())

/** The cue showing at [positionMs] (the TV's cueAt), by binary search on the sorted cues. */
fun cueAt(cues: List<Cue>, positionMs: Long): Cue? {
    var low = 0
    var high = cues.lastIndex
    var candidate = -1
    while (low <= high) {
        val mid = (low + high) ushr 1
        if (cues[mid].startMs <= positionMs) {
            candidate = mid
            low = mid + 1
        } else high = mid - 1
    }
    // Rolling auto-captions overlap; the latest started one still showing wins.
    for (i in candidate downTo maxOf(0, candidate - 3)) {
        if (positionMs < cues[i].endMs) return cues[i]
    }
    return null
}

/** "en" matches "en", "en-US" and "en-GB"; a regional preference matches only its region. */
fun languageMatches(trackLanguage: String, wanted: String): Boolean {
    val track = trackLanguage.lowercase(Locale.ROOT)
    val want = wanted.lowercase(Locale.ROOT)
    return track == want || (!want.contains('-') && track.substringBefore('-') == want)
}

internal fun withVttFormat(url: String): String = withFormat(url, "vtt")

internal fun withFormat(url: String, format: String): String =
    url.toHttpUrlOrNull()?.newBuilder()?.setQueryParameter("fmt", format)?.build()?.toString() ?: url

private fun absoluteUrl(url: String) = if (url.startsWith("/")) "https://www.youtube.com$url" else url

private fun displayLanguage(code: String): String =
    Locale.forLanguageTag(code).getDisplayName(Locale.getDefault()).ifBlank { code }

private fun JsonObject.string(key: String): String? =
    (this[key] as? JsonPrimitive)?.takeIf { it.isString }?.contentOrNull?.takeIf { it.isNotBlank() }
